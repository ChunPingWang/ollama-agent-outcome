package com.github.chunpingwang.ollamaagentoutcome.adapter.persistence;

import com.github.chunpingwang.ollamaagentoutcome.domain.DisplayName;
import com.github.chunpingwang.ollamaagentoutcome.domain.Email;
import com.github.chunpingwang.ollamaagentoutcome.domain.Profile;
import com.github.chunpingwang.ollamaagentoutcome.domain.ProfileId;

/**
 * 轉換器：在 Domain Profile 與 JPA Entity 之間進行映射。
 */
public class ProfileEntityConverter {

    Profile toDomain(ProfileJpaEntity entity) {
        return new Profile(
                new ProfileId(entity.getId()),
                new Email(entity.getEmail()),
                new DisplayName(entity.getDisplayName())
        );
    }

    ProfileJpaEntity toEntity(Profile profile) {
        // If the domain object has an ID, we treat it as existing or explicitly set.
        // isNew flag in entity handles insert vs update logic for JPA.
        ProfileJpaEntity entity = new ProfileJpaEntity();
        entity.setId(profile.getId().getId());
        entity.setEmail(profile.getEmail().getValue());
        entity.setDisplayName(profile.getDisplayName() != null ? profile.getDisplayName().getValue() : null);
        
        // Since we are passing a fully formed Profile with an ID (generated by domain), 
        // and not using DB auto-gen, we need to handle persistence correctly.
        // For 'save' semantics where ID is provided:
        // If it's truly new, merge will try to find it. If not found, it inserts.
        // However, standard JPA merge expects managed state or detached.
        // To ensure correct behavior with Persistable<UUID> and manual IDs:
        // We rely on the fact that if ID exists in DB, merge updates; if not, it might fail uniqueness or insert depending on provider config.
        // A safer approach for "Save" with pre-generated UUIDs without @GeneratedValue is often separate save/merge logic,
        // but given the constraints and typical Spring Data behavior with Merge:
        // If the record doesn't exist, merge throws EntityNotFoundException or similar unless configured otherwise? 
        // Actually, Hibernate's merge on a non-existent entity with an ID usually results in an update attempt which fails if row missing, 
        // OR if we use `persist` then we can't have an ID set yet.
        // Given the prompt instruction: "Domain 若自行產生識別碼... JPA Entity 不可同時使用 @GeneratedValue".
        // And "轉換器建立新 Entity 時保持 isNew = true".
        
        ProfileJpaEntity newEntity = new ProfileJpaEntity(
                profile.getId().getId(),
                profile.getEmail().getValue(),
                profile.getDisplayName() != null ? profile.getDisplayName().getValue() : null
        );
        return newEntity;
    }
}
